import { describe, expect, it } from 'vitest';
import { tripCalculationSource } from '../runtime';
import type { RoutePattern } from '../types';
import type { TripPlacement } from './routeFromFeed';
import { runtimeProfileFromFeed } from './runtimesFromFeed';
import { tripFromFeed } from './tripsFromFeed';
import type { FeedTrip } from './tripsOnDate';

const NOW = '2026-11-21T00:00:00.000Z';

const pattern: RoutePattern = {
  id: 'pattern-1',
  scenarioId: 'scenario-1',
  routeId: 'route-1',
  name: 'Outbound',
  points: [
    { id: 'p0', nodeId: 'n0', sequence: 0, cumulativeMiles: 0 },
    { id: 'p1', nodeId: 'n1', sequence: 1, cumulativeMiles: 1 },
  ],
  createdAt: NOW,
  updatedAt: NOW,
};

const profile = runtimeProfileFromFeed({
  pattern,
  serviceDayName: 'Weekday',
  trips: [{ pointTimes: [21600, 22200] }],
  now: NOW,
});

const feedTrip = (shortName?: string): FeedTrip => ({
  tripId: 'T1',
  sourceTripId: 'T1',
  routeId: 'R',
  serviceId: 'WK',
  stopTimes: [],
  ...(shortName === undefined ? {} : { shortName }),
});

// The first point is left at 06:00:00. The last point's departure (06:10:30) is not stored: the trip's time there is its arrival, 06:10:00.
const placement: TripPlacement = {
  tripId: 'T1',
  patternId: 'pattern-1',
  points: [
    { patternPointId: 'p0', departure: 21600, arrival: 21600, filled: false },
    { patternPointId: 'p1', departure: 22230, arrival: 22200, filled: false },
  ],
};

function build(overrides: { feed?: FeedTrip; placement?: TripPlacement } = {}) {
  return tripFromFeed({
    scenarioId: 'scenario-1',
    tripProfileId: 'trip-profile-1',
    routeId: 'route-1',
    serviceDayId: 'sd-weekday',
    feedTrip: overrides.feed ?? feedTrip('S-1'),
    placement: overrides.placement ?? placement,
    pattern,
    profile,
    now: NOW,
  });
}

describe('tripFromFeed (Decision 0089 items 31 and 40)', () => {
  it('stores the departure at each point and the arrival at the last point', () => {
    expect(build().stopTimes).toEqual([
      { patternPointId: 'p0', sequence: 0, time: 21600 },
      { patternPointId: 'p1', sequence: 1, time: 22200 },
    ]);
  });

  it('records the trip as generated by the feed, with the profile it was calculated from', () => {
    const trip = build();
    expect(trip.provenance).toEqual({
      kind: 'generated',
      creationMethod: 'feed',
      manuallyChangedFields: [],
      runtimeProfileId: profile.id,
      runtimeCalculationRevision: 0,
      calculationSource: tripCalculationSource(profile),
    });
    expect(trip).toMatchObject({ scenarioId: 'scenario-1', routeId: 'route-1', serviceDayId: 'sd-weekday', patternId: 'pattern-1', tripProfileId: 'trip-profile-1' });
  });

  it('uses trip_short_name as the public label, and leaves it unset when the feed has none', () => {
    expect(build().publicLabel).toBe('S-1');
    expect(build({ feed: feedTrip() })).not.toHaveProperty('publicLabel');
  });

  it('refuses a placement for another pattern or with another number of points', () => {
    expect(() => build({ placement: { ...placement, patternId: 'other' } })).toThrow(RangeError);
    expect(() => build({ placement: { ...placement, points: placement.points.slice(0, 1) } })).toThrow(RangeError);
  });
});
